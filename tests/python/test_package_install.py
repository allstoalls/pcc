def _write_demo_wheel(
    path: Path,
    *,
    requires: tuple[str, ...] = (),
    native_libpython: bool = False,
    cpython_extension_abi: bool = False,
) -> Path:
    metadata = "Name: demo-pkg\n"
    for dep in requires:
        metadata += f"Requires-Dist: {dep}\n"
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("demo_pkg/__init__.py", "VALUE = 1\n")
        zf.writestr(
            "demo_pkg/core.py",
            "def answer() -> int:\n" "    return 42\n",
        )
        if native_libpython:
            zf.writestr("demo_pkg/bad.so", "/usr/local/lib/libpython3.13.dylib\n")
        if cpython_extension_abi:
            zf.writestr("demo_pkg/_demo.cpython-314-darwin.so", "libpcc_runtime\n")
        zf.writestr("demo_pkg-0.1.dist-info/METADATA", metadata)
    return path


def _write_helper_wheel(path: Path) -> Path:
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("helper_pkg/__init__.py", "VALUE = 2\n")
        zf.writestr("helper_pkg/core.py", "def helper() -> int:\n    return 7\n")
        zf.writestr("helper_pkg-0.1.dist-info/METADATA", "Name: helper-pkg\n")
    return path


@contextmanager
def _serve_directory(root: Path):
    class Handler(SimpleHTTPRequestHandler):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, directory=str(root), **kwargs)

        def log_message(self, format, *args):  # noqa: A002
            return

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        host, port = server.server_address
        yield f"http://{host}:{port}"
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)


def _write_simple_index(root: Path, wheel: Path) -> str:
    simple = root / "simple" / "demo-pkg"
    simple.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
    href = "/packages/" + wheel.name + "#sha256=" + digest
    (simple / "index.html").write_text(
        f'<html><body><a href="{href}">{wheel.name}</a></body></html>\n',
        encoding="utf-8",
    )
    return "/simple"


