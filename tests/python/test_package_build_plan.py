REPO = repo_root()


def _find_current_pcc1() -> Path | None:
    return find_current_pcc1(REPO)


def _write_build_project(root: Path) -> Path:
    root.mkdir()
    (root / "demo_pkg").mkdir()
    (root / "demo_pkg" / "__init__.py").write_text("VALUE = 1\n", encoding="utf-8")
    (root / "demo_pkg.pyx").write_text("cdef int value\n", encoding="utf-8")
    (root / "demo_pkg.c").write_text(
        "/* Generated by Cython */\nint demo(void) { return 1; }\n",
        encoding="utf-8",
    )
    (root / "solver.f90").write_text("subroutine solver()\nend\n", encoding="utf-8")
    (root / "meson.build").write_text("project('demo_pkg', 'c')\n", encoding="utf-8")
    (root / "pyproject.toml").write_text(
        "[build-system]\n"
        "requires = ['meson-python', 'cython']\n"
        "build-backend = 'mesonpy'\n",
        encoding="utf-8",
    )
    (root / "compile_commands.json").write_text(
        json.dumps(
            [
                {
                    "file": str(root / "demo_pkg.c"),
                    "command": "cc -I include -DVALUE=1 -c demo_pkg.c -o demo_pkg.o -lopenblas",
                },
                {
                    "file": str(root / "solver.f90"),
                    "arguments": [
                        "gfortran",
                        "-I",
                        "finclude",
                        "-c",
                        "solver.f90",
                        "-o",
                        "solver.o",
                        "-llapack",
                    ],
                },
            ]
        ),
        encoding="utf-8",
    )
    return root


def _write_meson_only_project(root: Path) -> Path:
    root.mkdir()
    (root / "demo_pkg").mkdir()
    (root / "demo_pkg" / "__init__.py").write_text("VALUE = 1\n", encoding="utf-8")
    (root / "native.c").write_text(
        "int native_value(void) { return 1; }\n", encoding="utf-8"
    )
    (root / "solver.f90").write_text("subroutine solver()\nend\n", encoding="utf-8")
    (root / "meson.build").write_text(
        "project('demo_pkg', 'c', 'fortran')\n", encoding="utf-8"
    )
    meson_info = root / "meson-info"
    meson_info.mkdir()
    (meson_info / "intro-targets.json").write_text(
        json.dumps(
            [
                {
                    "name": "demo_native",
                    "target_sources": [
                        {
                            "language": "c",
                            "compiler": ["cc"],
                            "parameters": ["-DMESON_VALUE=1"],
                            "sources": ["native.c"],
                        },
                        {
                            "language": "fortran",
                            "compiler": ["gfortran"],
                            "parameters": [],
                            "sources": ["solver.f90"],
                        },
                    ],
                }
            ]
        ),
        encoding="utf-8",
    )
    return root


def test_build_plan_consumes_compile_commands_and_build_surfaces(tmp_path):
    project = _write_build_project(tmp_path / "demo_pkg-0.1")
    commands = load_compile_commands(project / "compile_commands.json")
    assert [command.language for command in commands] == ["c", "fortran"]
    assert commands[0].include_dirs == ("include",)
    assert commands[0].defines == ("VALUE=1",)
    assert commands[0].libraries == ("openblas",)
    assert commands[1].include_dirs == ("finclude",)
    assert commands[1].libraries == ("lapack",)

    plan = build_plan_for_artifact("demo-pkg", project).as_dict()
    assert plan["ok"] is True
    assert plan["source_summary"] == {"c": 1, "cxx": 0, "fortran": 1, "unknown": 0}
    assert "consume_compile_commands" in plan["actions"]
    assert "consume_generated_c" in plan["actions"]
    assert "consume_meson_plan" in plan["actions"]
    assert "delegate_fortran_toolchain" in plan["actions"]
    assert "detect_blas" in plan["actions"]
    assert "detect_lapack" in plan["actions"]
    assert "fortran_toolchain_required" in plan["diagnostics"]
    assert "blas_vendor_required" in plan["diagnostics"]
    assert "lapack_vendor_required" in plan["diagnostics"]


@pytest.mark.parametrize("shape", ["command", "arguments"])
def test_public_native_build_plan_json_consumes_canonical_command_records(tmp_path, shape):
    from pcc.driver.cli_bootstrap import _native_build_plan_json

    project = _write_build_project(tmp_path / "demo_pkg-0.1")
    entry = {"file": str(project / "demo_pkg.c"), "directory": str(project)}
    tokens = ["cc", "-I", "include path", "-DVALUE=1", "-c", "demo_pkg.c", "-o", "demo_pkg.o", "-lopenblas"]
    if shape == "arguments":
        entry["arguments"] = tokens
    else:
        entry["command"] = "cc -I 'include path' -DVALUE=1 -c demo_pkg.c -o demo_pkg.o -lopenblas"
    (project / "compile_commands.json").write_text(json.dumps([entry]))
    native = json.loads(_native_build_plan_json("demo-pkg", str(project)))
    canonical = build_plan_for_artifact("demo-pkg", project).as_dict()
    assert native["commands"] == canonical["commands"]
    assert native["commands"][0]["compiler"] == "cc"
    assert native["commands"][0]["include_dirs"] == ["include path"]
    assert native["commands"][0]["defines"] == ["VALUE=1"]
    assert native["commands"][0]["libraries"] == ["openblas"]
    assert native["source_summary"] == canonical["source_summary"]
    assert native["compile_commands"]["entries"] == 1


